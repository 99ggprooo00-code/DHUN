    private val byCode: Map<String, CountryRegion> = all.associateBy(CountryRegion::code)
    val default: CountryRegion = byCode.getValue("US")

    fun find(code: String?): CountryRegion? = code?.let(byCode::get)
    fun isSupportedCode(code: String): Boolean = code in byCode

    /** Search full names and codes, case-insensitively; preserve alphabetical order. */
    fun search(query: String): List<CountryRegion> {
        val term = query.trim()
        if (term.isEmpty()) return all
        return all.filter { it.name.contains(term, ignoreCase = true) || it.code.contains(term, ignoreCase = true) }
    }
