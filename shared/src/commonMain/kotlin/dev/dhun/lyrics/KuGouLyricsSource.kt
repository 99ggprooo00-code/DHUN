package dev.dhun.lyrics

import dev.dhun.core.DhunError
import dev.dhun.core.DhunResult
import dev.dhun.core.Lyrics
import dev.dhun.core.Track
import io.ktor.client.HttpClient
import io.ktor.client.request.get
import io.ktor.client.plugins.timeout
import io.ktor.client.request.parameter
import io.ktor.client.statement.bodyAsText
import io.ktor.http.isSuccess
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonPrimitive
import kotlin.io.encoding.Base64
import kotlin.math.abs

/** Public KuGou lyrics search/download (no credentials); LRC response is base64 UTF-8. */
class KuGouLyricsSource(
    private val client: HttpClient = LrcLibSource.defaultClient(),
    private val baseUrl: String = "https://lyrics.kugou.com",
) : LyricsSource {
    @OptIn(kotlin.io.encoding.ExperimentalEncodingApi::class)
    override suspend fun fetch(track: Track): DhunResult<Lyrics> {
        if (track.title.isBlank() || track.artistName.isBlank()) return DhunResult.Success(Lyrics.NotAvailable)
        return try {
            val search = client.get("$baseUrl/search") {
                timeout { requestTimeoutMillis = 12_000 }
                parameter("ver", 1); parameter("man", "yes"); parameter("client", "pc")
                parameter("keyword", "${track.artistName} - ${track.title}")
                parameter("duration", (track.durationSeconds ?: 0) * 1000)
            }
            if (!search.status.isSuccess()) return DhunResult.Success(Lyrics.NotAvailable)
            val root = Json.parseToJsonElement(search.bodyAsText()) as? JsonObject
            val candidates = root?.get("candidates") as? JsonArray
            val candidate = candidates?.filterIsInstance<JsonObject>()?.filter { item ->
                item["song"]?.jsonPrimitive?.content?.contains(track.title, ignoreCase = true) == true &&
                    item["singer"]?.jsonPrimitive?.content?.contains(track.artistName, ignoreCase = true) == true &&
                    (track.durationSeconds == null || abs((item["duration"]?.jsonPrimitive?.content?.toLongOrNull()
                        ?: 0L) - track.durationSeconds * 1000L) <= 10_000L)
            }?.minByOrNull {
                abs((it["duration"]?.jsonPrimitive?.content?.toLongOrNull() ?: 0L) -
                    (track.durationSeconds ?: 0) * 1000L)
            } ?: return DhunResult.Success(Lyrics.NotAvailable)
            val id = candidate["id"]?.jsonPrimitive?.content ?: return DhunResult.Success(Lyrics.NotAvailable)
            val key = candidate["accesskey"]?.jsonPrimitive?.content ?: return DhunResult.Success(Lyrics.NotAvailable)
            val response = client.get("$baseUrl/download") {
                timeout { requestTimeoutMillis = 12_000 }
                parameter("ver", 1); parameter("client", "pc"); parameter("id", id)
                parameter("accesskey", key); parameter("fmt", "lrc"); parameter("charset", "utf8")
            }
            if (!response.status.isSuccess()) return DhunResult.Success(Lyrics.NotAvailable)
            val body = Json.parseToJsonElement(response.bodyAsText()) as? JsonObject
            val encoded = body?.get("content")?.jsonPrimitive?.content ?: return DhunResult.Success(Lyrics.NotAvailable)
            val text = Base64.decode(encoded).decodeToString()
            // KuGou ships bilingual sets as TWO aligned documents: `content` is
            // the primary lyric and `contentts` the translation of the same
            // lines. Merging them needs an explicit overlay; concatenating the
            // documents would interleave two songs' worth of text.
            val translation = body["contentts"]?.jsonPrimitive?.contentOrNull
                ?.takeIf { it.isNotBlank() }
                ?.let { runCatching { Base64.decode(it).decodeToString() }.getOrNull() }
            val lines = LrcParser.parse(text, allowUnsyncedFallback = false)
                .let { primary -> applyTranslationOverlay(primary, translation) }
            if (lines.isNotEmpty()) DhunResult.Success(Lyrics.Synced(lines))
            else if (text.isNotBlank()) DhunResult.Success(Lyrics.Unsynced(text))
            else DhunResult.Success(Lyrics.NotAvailable)
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (_: Exception) {
            DhunResult.Failure(DhunError.Network())
        }
    }

    /**
     * Overlays a translation document onto [primary] by start time.
     *
     * Both documents are generated by the same provider for the same song, so
     * the line onsets line up; a translation line is only attached when its
     * start time matches exactly one primary line and the two texts differ.
     * Anything unmatched is dropped rather than guessed — a translation on the
     * wrong lyric is worse than no translation.
     */
    internal fun applyTranslationOverlay(
        primary: List<dev.dhun.core.LyricsLine>,
        translationDocument: String?,
    ): List<dev.dhun.core.LyricsLine> {
        if (translationDocument.isNullOrBlank() || primary.isEmpty()) return primary
        val translated = LrcParser.parse(translationDocument, allowUnsyncedFallback = false)
        if (translated.isEmpty()) return primary
        val byStart = translated.groupBy { it.startTimeMs }
        return primary.map { line ->
            val candidates = byStart[line.startTimeMs].orEmpty()
            val text = candidates.singleOrNull()?.text?.trim()
            if (text.isNullOrBlank() || text == line.text.trim()) line else line.copy(translation = text)
        }
    }
}
